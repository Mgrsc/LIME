    /**
     * History sanitizer: converts obsolete full-width general symbols to standard ASCII
     * while preserving math minus (− U+2212), typographic dashes (——) and ellipses (……).
     */
    fun sanitizeObsoleteSymbol(symbol: String): String {
        return when (symbol) {
            "＠" -> "@"
            "＃" -> "#"
            "＄" -> "$"
            "％" -> "%"
            "＾" -> "^"
            "＆" -> "&"
            "＊" -> "*"
            "＝" -> "="
            "＿" -> "_"
            "｀" -> "`"
            "＋" -> "+"
            "＼" -> "\\"
            "／" -> "/"
            "＜" -> "<"
            "＞" -> ">"
            "｜" -> "|"
            "．" -> "."
            "１" -> "1"
            "２" -> "2"
            "３" -> "3"
            "４" -> "4"
            "５" -> "5"
            "６" -> "6"
            "７" -> "7"
            "８" -> "8"
            "９" -> "9"
            "０" -> "0"
            else -> symbol
        }
    }

